/**
 * Writes meta.ts, events.ts, dont-miss.ts, descriptions.ts, changes.ts, venues.ts, and about.ts for the pages and
 * islands to import (seven modules so each page and island ships only what it renders; descriptions go to the event
 * page alone, the changes to the changes page, and the venues and what the site says about the job to the Astro
 * pages), and events.json in the public directory: the published events with their descriptions, never the job's raw
 * file, whose evidence, leads, counters, and held-back records stay in git. Paths and the clock are parameters so a
 * test can write somewhere else.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { PublishedDataset } from "../lib/types";
import { loadPublished } from "./load-dataset.ts";

/**
 * The shape of the public events.json; bumped by hand when a field is removed or changes meaning. It starts at 2
 * because the job's raw file, version 1, was served at the same URL until #89.
 */
export const PUBLISHED_SCHEMA_VERSION = 2;

/** What the front page may weigh on real data: HTML, CSS, and JS, gzipped. */
export const FRONT_PAGE_BYTES = 50_500; // 50 KB, plus 200 bytes for a run's days (#143) and 300 for the calendar subscription line (#136)
/**
 * The most don't-miss picks the front page was sized for: its code budget, measured on the fixture build, leaves room
 * in FRONT_PAGE_BYTES for this many (scripts/size-check.ts). A week over it is a warning, not a failed deploy.
 */
export const MAX_PICKS = 20;

export function writeGenerated(opts: { datasetPath: string; configPath: string; venuesPath?: string; outDir: string; publicDir: string; today?: string; now?: Date }): { eventCount: number; buildToday: string } {
  const { events, descriptions, about, changes, venues, ...meta } = loadPublished({
    datasetPath: opts.datasetPath,
    configPath: opts.configPath,
    ...(opts.venuesPath === undefined ? {} : { venuesPath: opts.venuesPath }),
    ...(opts.today === undefined ? {} : { today: opts.today }),
  });

  mkdirSync(opts.outDir, { recursive: true });
  const header = "// Generated by src/build/generate.ts from the dataset; do not edit.\n";
  writeFileSync(join(opts.outDir, "meta.ts"), `${header}import type { PublishedMeta } from "../lib/types";\nexport const meta: PublishedMeta = ${JSON.stringify(meta)};\n`);
  writeFileSync(join(opts.outDir, "events.ts"), `${header}import type { PublishedEvent } from "../lib/types";\nexport const events: PublishedEvent[] = ${JSON.stringify(events)};\n`);
  writeFileSync(join(opts.outDir, "descriptions.ts"), `${header}import type { PublishedDescriptions } from "../lib/types";\nexport const descriptions: PublishedDescriptions = ${JSON.stringify(descriptions)};\n`);
  writeFileSync(join(opts.outDir, "changes.ts"), `${header}import type { PublishedChanges } from "../lib/types";\nexport const changes: PublishedChanges = ${JSON.stringify(changes)};\n`);
  writeFileSync(join(opts.outDir, "venues.ts"), `${header}import type { PublishedVenue } from "../lib/types";\nexport const venues: PublishedVenue[] = ${JSON.stringify(venues)};\n`);
  writeFileSync(join(opts.outDir, "about.ts"), `${header}import type { PublishedAbout } from "../lib/types";\nexport const about: PublishedAbout = ${JSON.stringify(about)};\n`);
  const dontMiss = events.filter((e) => e.dontMiss);
  writeFileSync(join(opts.outDir, "dont-miss.ts"), `${header}import type { PublishedEvent } from "../lib/types";\nexport const dontMiss: PublishedEvent[] = ${JSON.stringify(dontMiss)};\n`);
  if (dontMiss.length > MAX_PICKS) {
    console.warn(`site: ${dontMiss.length} don't-miss picks, over the ${MAX_PICKS} the front page's ${FRONT_PAGE_BYTES / 1000} KB budget was sized for; curation is flagging more than it should`);
  }

  mkdirSync(opts.publicDir, { recursive: true });
  const published: PublishedDataset = {
    schemaVersion: PUBLISHED_SCHEMA_VERSION,
    generatedAt: (opts.now ?? new Date()).toISOString(),
    lastSuccessfulRun: meta.lastSuccessfulRun,
    events: events.map((e) => (descriptions[e.id] === undefined ? e : { ...e, description: descriptions[e.id]! })),
  };
  writeFileSync(join(opts.publicDir, "events.json"), JSON.stringify(published));
  return { eventCount: events.length, buildToday: meta.buildToday };
}
