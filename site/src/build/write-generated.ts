/**
 * Writes meta.ts, events.ts, and dont-miss.ts for the pages and islands to import (three modules so each island
 * ships only what it renders), and copies the dataset byte for byte to events.json in the public directory (the
 * published contract, never re-serialized). Paths are parameters so a test can write somewhere else.
 */
import { copyFileSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { loadPublished } from "./load-dataset.ts";

export function writeGenerated(opts: { datasetPath: string; configPath: string; outDir: string; publicDir: string; today?: string }): { eventCount: number; buildToday: string } {
  const { events, ...meta } = loadPublished({ datasetPath: opts.datasetPath, configPath: opts.configPath, ...(opts.today === undefined ? {} : { today: opts.today }) });

  mkdirSync(opts.outDir, { recursive: true });
  const header = "// Generated by src/build/generate.ts from the dataset; do not edit.\n";
  writeFileSync(join(opts.outDir, "meta.ts"), `${header}import type { PublishedMeta } from "../lib/types";\nexport const meta: PublishedMeta = ${JSON.stringify(meta)};\n`);
  writeFileSync(join(opts.outDir, "events.ts"), `${header}import type { PublishedEvent } from "../lib/types";\nexport const events: PublishedEvent[] = ${JSON.stringify(events)};\n`);
  writeFileSync(join(opts.outDir, "dont-miss.ts"), `${header}import type { PublishedEvent } from "../lib/types";\nexport const dontMiss: PublishedEvent[] = ${JSON.stringify(events.filter((e) => e.dontMiss))};\n`);

  mkdirSync(opts.publicDir, { recursive: true });
  copyFileSync(opts.datasetPath, join(opts.publicDir, "events.json"));
  return { eventCount: events.length, buildToday: meta.buildToday };
}
